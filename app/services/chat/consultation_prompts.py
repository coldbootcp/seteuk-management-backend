def build_progress_block(progress: dict[str, Any]) -> str:
    """세션에 저장된 사실로 계산한 진행 상태. 모델이 대화 기록만 보고 단계를
    추측하지 않게, 무엇이 이미 정해졌는지를 매 턴 명시한다."""
    stage = progress.get("stage", STAGE_FLOW)
    payload = {
        "current_stage": stage,
        "stage_label": STAGE_LABELS.get(stage, stage),
        "target_semester": progress.get("target_label"),
        "remaining_semesters": progress.get("remaining_semesters", []),
        "three_year_flow_draft": progress.get("flow"),
        "three_year_flow_confirmed": progress.get("flow_confirmed", False),
        "semester_goal": progress.get("semester_goal"),
        "topic_draft_saved": progress.get("has_draft_plan", False),
    }
    instruction = _STAGE_INSTRUCTIONS.get(stage, "")
    return (
        f"<상담_진행_상태>\n{json.dumps(payload, ensure_ascii=False)}\n</상담_진행_상태>\n"
        f"[이번 턴의 지시] {instruction}"
    )

