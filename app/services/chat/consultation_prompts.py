def build_consultation_system_prompt(
    kind: str,
    context_json: str,
    roadmap_summary_json: str | None,
    progress: dict[str, Any] | None = None,
) -> str:
    if kind == "graduate_fit":
        # 졸업생은 로드맵이 없고 만들지도 않으므로 <기존_3개년_계획>을 붙이지 않는다.
        return (
            f"{GRADUATE_FIT_CONSULTATION_PROMPT}\n\n<학생_데이터>\n{context_json}\n</학생_데이터>"
        )
    base = (
        INITIAL_CONSULTATION_PROMPT
        if kind == "initial"
        else SEMESTER_REVIEW_CONSULTATION_PROMPT
    )
    prompt = f"{base}\n\n<학생_데이터>\n{context_json}\n</학생_데이터>"
    if roadmap_summary_json:
        prompt += f"\n\n<기존_3개년_계획>\n{roadmap_summary_json}\n</기존_3개년_계획>"
    if progress is not None:
        prompt += "\n\n" + build_progress_block(progress)
    return prompt
